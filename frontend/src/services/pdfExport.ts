import { jsPDF } from 'jspdf';
import { SummarizeResponse, ResearchReportData } from '../types';

export function exportSummaryToPdf(data: SummarizeResponse) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  let cursorY = 22;

  // Header Bar
  doc.setFillColor(3, 7, 18);
  doc.rect(0, 0, pageWidth, 28, 'F');
  
  doc.setTextColor(0, 240, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('NEUROSUM AI — RESEARCH REPORT', margin, 14);

  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text('A Hybrid Extractive-Abstractive Framework with Factual Consistency Optimization', margin, 21);

  cursorY = 38;

  // Document Title & Metadata
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(data.title || 'Academic Document Summary', margin, cursorY);
  cursorY += 7;

  doc.setTextColor(100, 116, 139);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(`Document ID: ${data.id.substring(0, 8)}... | Date: ${new Date().toLocaleDateString()}`, margin, cursorY);
  cursorY += 10;

  // Metrics Summary Table Card
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(margin, cursorY, contentWidth, 22, 2, 2, 'F');
  
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  
  const colW = contentWidth / 4;
  doc.text(`FCS Score: ${data.metrics.factual_consistency_score}%`, margin + 4, cursorY + 8);
  doc.text(`Compression: ${data.metrics.compression_ratio}%`, margin + colW + 4, cursorY + 8);
  doc.text(`ROUGE-1: ${data.metrics.rouge.rouge1}`, margin + colW * 2 + 4, cursorY + 8);
  doc.text(`ROUGE-L: ${data.metrics.rouge.rougeL}`, margin + colW * 3 + 4, cursorY + 8);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text(`Claims: ${data.metrics.supported_claims_count}/${data.metrics.total_claims_count} Supported`, margin + 4, cursorY + 16);
  doc.text(`Words: ${data.metrics.word_count_final} (from ${data.metrics.word_count_original})`, margin + colW + 4, cursorY + 16);
  doc.text(`ROUGE-2: ${data.metrics.rouge.rouge2}`, margin + colW * 2 + 4, cursorY + 16);
  doc.text(`Latency: ${data.metrics.execution_time_ms.total_pipeline}ms`, margin + colW * 3 + 4, cursorY + 16);

  cursorY += 32;

  // SECTION 1: FINAL OPTIMIZED SUMMARY
  doc.setTextColor(2, 132, 199);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('1. FINAL OPTIMIZED & FACTUALLY VERIFIED SUMMARY', margin, cursorY);
  cursorY += 6;

  doc.setTextColor(30, 41, 59);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const finalLines = doc.splitTextToSize(data.final_summary, contentWidth);
  doc.text(finalLines, margin, cursorY);
  cursorY += finalLines.length * 5.2 + 8;

  // SECTION 2: ABSTRACTIVE DRAFT
  if (cursorY < 230) {
    doc.setTextColor(100, 116, 139);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('2. LLM Abstractive Draft (Pre-Verification):', margin, cursorY);
    cursorY += 5;

    doc.setTextColor(71, 85, 105);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    const absLines = doc.splitTextToSize(data.abstractive_summary, contentWidth);
    doc.text(absLines, margin, cursorY);
    cursorY += absLines.length * 4.8 + 8;
  }

  // SECTION 3: EXTRACTIVE CORE
  if (cursorY < 240) {
    doc.setTextColor(100, 116, 139);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('3. GAN-Selected Extractive Propositions:', margin, cursorY);
    cursorY += 5;

    doc.setTextColor(71, 85, 105);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    const extLines = doc.splitTextToSize(data.extractive_summary, contentWidth);
    doc.text(extLines, margin, cursorY);
    cursorY += extLines.length * 4.5 + 8;
  }

  // Footer
  doc.setTextColor(148, 163, 184);
  doc.setFontSize(7.5);
  doc.text('Generated by NeuroSum AI — Intelligent Hybrid Text Summarization & Factual Verification System', margin, 287);

  const safeFilename = (data.title || 'NeuroSum_Report')
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '_')
    .substring(0, 30);
  doc.save(`${safeFilename}_summary_report.pdf`);
}

export function exportResearchReportPdf(report: ResearchReportData) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  let cursorY = 22;

  // Top Header Banner
  doc.setFillColor(3, 7, 18);
  doc.rect(0, 0, pageWidth, 30, 'F');

  doc.setTextColor(0, 240, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text('NEUROSUM AI — RESEARCH BENCHMARK REPORT', margin, 13);

  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text('Academic Model Comparison & Factual Consistency Evaluation Report', margin, 19);
  doc.text(`Report ID: ${report.report_id}  |  Generated: ${report.generated_at}`, margin, 25);

  cursorY = 40;

  // Project Title
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Project Title:', margin, cursorY);
  cursorY += 5;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(51, 65, 85);
  const titleLines = doc.splitTextToSize(report.project_title, contentWidth);
  doc.text(titleLines, margin, cursorY);
  cursorY += titleLines.length * 4.8 + 6;

  // Dataset & Experimental Setup Card
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, cursorY, contentWidth, 24, 2, 2, 'FD');

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('Dataset & Partitioning Information:', margin + 4, cursorY + 7);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);
  doc.text(`Dataset: ${report.dataset_info.name} (${report.dataset_info.total_rows} total rows)`, margin + 4, cursorY + 13);
  doc.text(`Partitioning: Train (${report.dataset_info.split_distribution.train}) / Val (${report.dataset_info.split_distribution.validation}) / Test (${report.dataset_info.split_distribution.test})`, margin + 4, cursorY + 18);
  doc.text(`Test Partition Evaluated: ${report.dataset_info.test_partition_size} Documents (Strict disjoint separation without data leakage)`, margin + 4, cursorY + 23);

  cursorY += 32;

  // Benchmark Comparison Table Header
  doc.setTextColor(2, 132, 199);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.text('EXPERIMENTAL MODEL COMPARISON ON TEST SET', margin, cursorY);
  cursorY += 6;

  // Table header
  doc.setFillColor(15, 23, 42);
  doc.rect(margin, cursorY, contentWidth, 8, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'bold');

  doc.text('Model Architecture', margin + 2, cursorY + 5.5);
  doc.text('ROUGE-1', margin + 55, cursorY + 5.5);
  doc.text('ROUGE-2', margin + 75, cursorY + 5.5);
  doc.text('ROUGE-L', margin + 95, cursorY + 5.5);
  doc.text('FCS (%)', margin + 115, cursorY + 5.5);
  doc.text('Redundancy', margin + 135, cursorY + 5.5);
  doc.text('Latency', margin + 158, cursorY + 5.5);
  cursorY += 8;

  // Table rows
  report.summary_results_table.forEach((row, i) => {
    if (row.is_proposed) {
      doc.setFillColor(240, 253, 250);
      doc.setTextColor(13, 148, 136);
    } else {
      doc.setFillColor(i % 2 === 0 ? 255 : 248, i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 252);
      doc.setTextColor(51, 65, 85);
    }
    doc.rect(margin, cursorY, contentWidth, 8, 'F');
    doc.setFont('helvetica', row.is_proposed ? 'bold' : 'normal');
    doc.setFontSize(7.5);

    doc.text(row.approach, margin + 2, cursorY + 5.5);
    doc.text(String(row.rouge1), margin + 55, cursorY + 5.5);
    doc.text(String(row.rouge2), margin + 75, cursorY + 5.5);
    doc.text(String(row.rougeL), margin + 95, cursorY + 5.5);
    doc.text(String(row.factual_consistency), margin + 115, cursorY + 5.5);
    doc.text(String(row.redundancy), margin + 135, cursorY + 5.5);
    doc.text(String(row.latency_ms), margin + 158, cursorY + 5.5);
    cursorY += 8;
  });

  cursorY += 6;

  // Section 2: Discussion of Findings
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.text('DISCUSSION OF EMPIRICAL FINDINGS', margin, cursorY);
  cursorY += 5;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(51, 65, 85);
  const discLines = doc.splitTextToSize(report.findings_discussion, contentWidth);
  doc.text(discLines, margin, cursorY);
  cursorY += discLines.length * 4.3 + 6;

  // Section 3: Limitations
  if (cursorY < 235) {
    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('METHODOLOGICAL LIMITATIONS', margin, cursorY);
    cursorY += 5;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(71, 85, 105);
    const limLines = doc.splitTextToSize(report.limitations, contentWidth);
    doc.text(limLines, margin, cursorY);
  }

  // Footer
  doc.setTextColor(148, 163, 184);
  doc.setFontSize(7);
  doc.text('Generated by NEUROSUM AI Research Platform. Formal academic demonstration artifact.', margin, 288);

  const safeName = (report.dataset_info.name || 'NeuroSum')
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '_')
    .substring(0, 25);
  doc.save(`neurosum_research_report_${safeName}.pdf`);
}
